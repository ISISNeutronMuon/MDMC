"""
Contains formatted configuration data for solvent molecules, as well as a
helper function to convert the formatted configurations into a list of
Molecule objects.
"""

import numpy as np

from MDMC.MD.structural_units import Atom, Molecule


def molec_from_dict(mol_dict):

    """
    Creates a Molecule object from a dictionary containing atom and
    position pairs of the form:
        {str: np.ndarray}
        where the str represents the atom (i.e. 'H1', 'H2', or 'O')
        and the np.ndarray is the atomic position.
    """

    atoms = []
    for atom_key in mol_dict.keys():
        atoms.append(Atom(atom_key.replace('1', '').replace('2', ''),
                          position=mol_dict[atom_key]))
    return Molecule(atoms=atoms)

def molec_list_from_config(config):

    """
    Generates a list of Molecule objects from a formatted dictionary
    of solvent molecules and their constituent atomic positions of the form:
        {int: dict}
        where the int is the index of the molecule
        and the dict is of the form:
            {str: np.ndarray}
            where the str represents the atom (i.e. 'H1', 'H2', or 'O')
            and the np.ndarray is the atomic position.

    Returns
    -------
    molecules : list of Molecule
        Molecule objects generated from the atoms passed in config, where
        each molecule position is its centre-of-mass.
    """

    molecules = []
    for mol_dict in config.values():
        mol = molec_from_dict(mol_dict)
        molecules.append(mol)
    return molecules

